    // entry of group l and its seven high bits select a row of the shared sign table. Scale byte ib at block byte
    // 66 + ib keeps the sub-block's first two groups in its low nibble and its last two in its high nibble, read back
    // as ls = 2*nibble + 1 for the integer dot. Grid magnitudes stay unsigned, each group's sign row folds onto the
    // Q8_K activation quants instead of the weight, and sumf takes d * bsum once per super-block with 0.125f applied
    // once at the end - one shared float sequence over an integer total each path computes exactly.
    private static float RowDotIQ2XSQ8Scalar(byte* row, byte* qa, float* da, int cols)
    {
        Span<byte> mag = stackalloc byte[32]; // magnitude bytes of the current 32-value sub-block
        int blocks = Q8KBlockCount(cols); // whole super-blocks: padding columns quantize to zero and contribute nothing
        float sumf = 0f;

        for (int bi = 0; bi < blocks; bi++)
        {
            byte* block = row + (long)bi * IQ2XsBlockBytes;
            float d = ReadHalfLE(block) * da[bi]; // half-float weight scale times the activation block scale, reference order
            int bsum = 0;

            for (int ib = 0; ib < 8; ib++)
            {
                byte scaleByte = block[66 + ib]; // one byte carries the sub-block's two scale codes
                uint signs = StageIQ2XSMagnitudes(block + 2 + 8 * ib, mag);

                int lo;
                int hi;

                fixed (byte* pMag = mag)
                {
                    SubBlockDotQ8KScalar(pMag, signs, (sbyte*)(qa + bi * QkK + ib * 32), out lo, out hi);
                }

                // The reference splits sumi at the sub-block's halfway point: ls1 = 2*(scale & 0xF) + 1 covers groups
                // 0..1 and ls2 = 2*(scale >> 4) + 1 covers groups 2..3, matching SubBlockDotQ8KScalar's two halves.
                bsum += lo * (2 * (scaleByte & 0xF) + 1);
                bsum += hi * (2 * (scaleByte >> 4) + 1);
            }

            sumf += d * bsum;
        }

        return 0.125f * sumf;
    }

    // AVX2: the same staged magnitudes and packed sign bytes feed SubBlockDotQ8KAvx2 (the grid stays looked up through
    // staging because a 512-entry table of eight-byte entries cannot be reached by one pshufb), together with the two
    // sub-block scale nibbles. Its pmaddubsw/pmaddwd lane totals are exactly the scalar loop's running total, so only
    // the float accumulation order matters there - and it is shared, step for step, with RowDotIQ2XSQ8Scalar. The Q8_K
    // quants of a sub-block are already contiguous activation bytes, so nothing needs staging on that side either.
    private static float RowDotIQ2XSQ8Avx2(byte* row, byte* qa, float* da, int cols)
    {
        Span<byte> mag = stackalloc byte[32]; // magnitude bytes of the current 32-value sub-block
        int blocks = Q8KBlockCount(cols); // whole super-blocks: padding columns quantize to zero and contribute nothing
        float sumf = 0f;

        for (int bi = 0; bi < blocks; bi++)
        {
            byte* block = row + (long)bi * IQ2XsBlockBytes;
            float d = ReadHalfLE(block) * da[bi]; // half-float weight scale times the activation block scale, reference order
            int bsum = 0;

            for (int ib = 0; ib < 8; ib++)
            {
                byte scaleByte = block[66 + ib]; // one byte carries the sub-block's two scale codes
                uint signs = StageIQ2XSMagnitudes(block + 2 + 8 * ib, mag);

                int lo;
                int hi;

                fixed (byte* pMag = mag)
                {
                    SubBlockDotQ8KAvx2(pMag, signs, (sbyte*)(qa + bi * QkK + ib * 32), out lo, out hi);
                }

                bsum += lo * (2 * (scaleByte & 0xF) + 1); // ls1 over groups 0..1 and ls2 over groups 2..3, as in the scalar path
                bsum += hi * (2 * (scaleByte >> 4) + 1);
            }

            sumf += d * bsum;
        }

        return 0.125f * sumf;
    }

    // Stage one IQ2_XS sub-block: each group's packed grid word splits into a nine-bit table index and a seven-bit
    // sign-group code. The entry is read as one unaligned ulong in element order, the code selects a row of the shared
    // sign table, and the four sign bytes pack back at byte l. Identical staging for both dot paths and every vector of
    // a batch, which is what makes their results bit-identical.
    private static uint StageIQ2XSMagnitudes(byte* qs, Span<byte> mag)
    {
        fixed (byte* pGrid = GetIq2XSGrid())
        fixed (byte* pMag = mag)
        {
            uint signs = 0;

            for (int l = 0; l < 4; l++)
            {
                ushort word = ReadIQ2XsWordLE(qs + 2 * l); // one grid word carries one whole eight-value group
                Unsafe.WriteUnaligned(pMag + 8 * l, Unsafe.ReadUnaligned<ulong>(pGrid + (nint)(word & 511) * 8));
                signs |= (uint)GetKSignsIQ2XS()[word >> 9] << (8 * l); // seven-bit sign-group code of the group
            }

            return signs;
        }
    }

    // IQ2_XS sub-block staging: for each of the four eight-value groups, take the group's sign byte from the shared
    // sign table through the grid word's seven high bits, gather the referenced grid entry's eight magnitude bytes into
    // one broadcast vector (byte lanes 0..7 in element order), widen them with sign (pmovsxbd) so every byte lands as
    // its exact integer value, multiply by the group's sub-block scale, and flip the selected lanes by XOR-ing the
    // float sign bit (exact for every finite value, matching the reference multiply by -1.f). The staged weights land
    // in element order so the fused chunks match the scalar oracle.
    private static void FillIQ2XSSubBlock(byte* qs, float dbLo, float dbHi, Span<float> stage)
    {
        fixed (float* pStage = stage)
        {
            ReadOnlySpan<byte> gridTable = GetIq2XSGrid();

            for (int l = 0; l < 4; l++)
            {
                ushort word = ReadIQ2XsWordLE(qs + 2 * l);
                byte signs = GetKSignsIQ2XS()[word >> 9];

                // Eight magnitude bytes of the referenced entry, combined little-endian into one broadcast vector.
                int off = (word & 511) * 8;
                ulong low = (uint)(gridTable[off] | (gridTable[off + 1] << 8) | (gridTable[off + 2] << 16) | (gridTable[off + 3] << 24));
                ulong high = (uint)(gridTable[off + 4] | (gridTable[off + 5] << 8) | (gridTable[off + 6] << 16) | (gridTable[off + 7] << 24));
                Vector128<sbyte> magnitudes = Vector128.Create(low | (high << 32)).AsSByte();
                Vector128<int> magLo = Sse41.ConvertToVector128Int32(magnitudes); // bytes 0..3 -> dword lanes (pmovsxbd, magnitudes all < 128)
                Vector128<int> magHi = Sse41.ConvertToVector128Int32(Ssse3.Shuffle(magnitudes.AsByte(), GetUpperBytesShuffle()).AsSByte()); // bytes 4..7 -> dword lanes

                float dbLocal = l < 2 ? dbLo : dbHi;
                Vector128<float> dbV = Avx.BroadcastScalarToVector128(&dbLocal);
                Vector128<float> wLo = Sse.Multiply(Avx.ConvertToVector128Single(magLo), dbV); // cvtdq2ps then scale
                Vector128<float> wHi = Sse.Multiply(Avx.ConvertToVector128Single(magHi), dbV);

                Sse.Store(pStage + l * 8, Avx2.Xor(wLo.AsInt32(), SignMaskIQ2XS(signs, 0)).AsSingle());
                Sse.Store(pStage + l * 8 + 4, Avx2.Xor(wHi.AsInt32(), SignMaskIQ2XS(signs, 4)).AsSingle());
            }
        }
    }

    // Batched IQ2_XS row against Q8_K activations: each sub-block's magnitudes and sign bytes are staged once, then
    // applied to every vector's activation quants in RowDotIQ2XSQ8Avx2's integer and float order, so the packed weight
    // bytes are streamed one time for the whole batch. Each vector keeps its own exact int32 super-block total.
    private static void BatchIQ2XSQ8_Avx2(byte* row, byte* qa, float* da, int blocks, int count, int rows, float* outBase)
    {
        Span<byte> mag = stackalloc byte[32]; // magnitude bytes of the current 32-value sub-block
        Span<int> bsum = stackalloc int[MaxBatch]; // exact per-vector integer super-block totals
        Span<float> sumf = stackalloc float[MaxBatch];

        for (int bi = 0; bi < blocks; bi++)
        {
            byte* block = row + (long)bi * IQ2XsBlockBytes;
            float dw = ReadHalfLE(block); // half-float weight scale, multiplied by each vector's activation scale in the reference order

            for (int ib = 0; ib < 8; ib++)
            {
                byte scaleByte = block[66 + ib]; // one byte carries the sub-block's two scale codes
                int ls1 = 2 * (scaleByte & 0xF) + 1;
                int ls2 = 2 * (scaleByte >> 4) + 1;

                fixed (byte* pMag = mag)
                {
                    uint signs = StageIQ2XSMagnitudes(block + 2 + 8 * ib, mag); // decoded once per sub-block and reused across the batch
                    for (int b = 0; b < count; b++)
                    {
                        SubBlockDotQ8KAvx2(pMag, signs, (sbyte*)(qa + (long)b * blocks * QkK + bi * QkK + ib * 32), out int lo, out int hi);
                        bsum[b] += lo * ls1;
                        bsum[b] += hi * ls2;
                    }
                }
            }

            for (int b = 0; b < count; b++)
            {
                sumf[b] += (dw * da[(long)b * blocks + bi]) * bsum[b]; // same float grouping as the single-vector kernel
                bsum[b] = 0;
            }
        }

        for (int b = 0; b < count; b++)
        {
            outBase[(long)b * rows] = 0.125f * sumf[b]; // the reference's single final factor, applied exactly as in RowDotIQ2XSQ8Avx2
        }
    }

    // IQ2_XS row expansion: w = db * grid byte, sign-applied through the sign table, per element. Same grid/sign
    // staging FillIQ2XSSubBlock provides, storing the staged weights instead of dotting them.
    private static void DequantIQ2XSAvx2(byte* row, float* outPtr, int cols)
    {
        Span<float> stage = stackalloc float[32]; // staging buffer for the current 32-value sub-block

        for (int baseIdx = 0; baseIdx < cols; baseIdx += QkK)
        {
            byte* block = row + (long)(baseIdx / QkK) * IQ2XsBlockBytes;
            float dHalf = ReadHalfLE(block);

            for (int ib = 0; ib < 8; ib++)
            {
                int subStart = baseIdx + ib * 32;
                if (subStart >= cols)
                {
                    break; // zero-padded tail block: no elements left to consume.
                }

                float dbLo = dHalf * (0.5f + (block[66 + ib] & 0xF)) * 0.25f;
                float dbHi = dHalf * (0.5f + (block[66 + ib] >> 4)) * 0.25f;
                int limit = Math.Min(32, cols - subStart); // padded quants are zero: stop at the real column count.

                FillIQ2XSSubBlock(block + 2 + 8 * ib, dbLo, dbHi, stage);

                fixed (float* pStage = stage)
                {
                    for (int c = 0; c + 8 <= limit; c += 8)
                    {
                        Avx.Store(outPtr + subStart + c, Avx.LoadVector256(pStage + c)); // staged weights, materialized once per sub-block
                    }
                }

                for (int l = (limit / 8) * 8; l < limit; l++)
                {
                    outPtr[subStart + l] = stage[l]; // partial final chunk: at most seven elements per sub-block
                }
            }
        }
    }
