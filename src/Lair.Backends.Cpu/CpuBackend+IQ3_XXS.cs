        int blocks = Q8KBlockCount(cols); // whole super-blocks: padding columns quantize to zero and contribute nothing
        float sumf = 0f;

        for (int bi = 0; bi < blocks; bi++)
        {
            byte* block = row + (long)bi * IQ3XxsBlockBytes;
            float d = ReadHalfLE(block) * da[bi]; // half-float weight scale times the activation block scale, reference order
            byte* qs = block + 2; // grid-index region: bytes [qs, qs+64) always inside the block
            int bsum = 0;

            for (int ib = 0; ib < 8; ib++)
            {
                uint aux = ReadIQ3AuxLE(qs + QkK / 4 + 4 * ib);
                uint signs = StageIQ3XMagnitudes(qs + 8 * ib, aux, mag, opts.Grid);

                int lo;
                int hi;

                fixed (byte* pMag = mag)
                {
                    SubBlockDotQ8KVector(pMag, signs, (sbyte*)(qa + bi * QkK + ib * 32), out lo, out hi, opts.Dot);
                }

                bsum += (lo + hi) * (2 * (int)(aux >> 28) + 1); // one ls covers the whole sub-block, as in the scalar path
            }

            sumf += d * bsum;
        }

        return 0.25f * sumf;
    }

    // Stage one IQ3_XXS sub-block: each of the four groups takes two consecutive grid indices, each entry read as one
    // unaligned uint, so the group's eight magnitude bytes land in element order (entry A covers values 0..3 and entry
    // B values 4..7 of the group, exactly the reference's grid1/grid2 pairing); the group's seven-bit sign code selects
    // a row of the shared sign table and packs back at byte l. Identical staging for both dot paths and every vector of
    // a batch.
    private static uint StageIQ3XMagnitudes(byte* qs, uint aux, Span<byte> mag, GridLoadEncoding grid)
    {
        fixed (byte* pGrid = GetIq3XXSGrid())
        fixed (byte* pMag = mag)
        {
            uint signs = 0;

            if (grid == GridLoadEncoding.Gather && Avx2.IsSupported)
            {
                // Hardware gather over whole entries: each lane's byte offset selects one four-byte entry, so the sub-block's
                // eight indices stage their magnitude bytes in element order from a single dword gather instead of eight
                // dependent indexed loads. The gathered dwords land exactly where scalar staging writes its A/B pairs.
                Vector256<int> offsets = Vector256.Create(
                    qs[0] * 4,
                    qs[1] * 4,
                    qs[2] * 4,
                    qs[3] * 4,
                    qs[4] * 4,
                    qs[5] * 4,
                    qs[6] * 4,
                    qs[7] * 4);

                Vector256<uint> gathered = Avx2.GatherVector256((uint*)pGrid, offsets, 1); // each lane gathers one entry raw: bits copied unchanged.
                Unsafe.WriteUnaligned(pMag, gathered);

                for (int l = 0; l < 4; l++)
                {
                    signs |= (uint)GetKSignsIQ2XS()[(int)((aux >> (7 * l)) & 127)] << (8 * l);
                }

                return signs;
            }

            for (int l = 0; l < 4; l++)
            {
                Unsafe.WriteUnaligned(pMag + 8 * l, Unsafe.ReadUnaligned<uint>(pGrid + (nint)qs[2 * l] * 4));
                Unsafe.WriteUnaligned(pMag + 8 * l + 4, Unsafe.ReadUnaligned<uint>(pGrid + (nint)qs[2 * l + 1] * 4));
                signs |= (uint)GetKSignsIQ2XS()[(int)((aux >> (7 * l)) & 127)] << (8 * l);
            }

            return signs;
        }
    }

    // IQ3_XXS sub-block staging: for each of the four eight-value groups, gather the two referenced grid entries'
    // magnitude bytes into one broadcast pair (byte lanes 0..7 hold entry A then entry B in element order), widen them
    // with sign (pmovsxbd) so every byte lands as its exact integer value, multiply by db, and flip the selected lanes
    // by XOR-ing the float sign bit (exact for every finite value, matching the reference multiply by -1.f). The staged
    // weights land in element order so the fused chunks match the scalar oracle.
    private static void FillIQ3SubBlock(byte* qs, uint aux, float db, Span<float> stage)
    {
        fixed (float* pStage = stage)
        {
            ReadOnlySpan<byte> gridTable = GetIq3XXSGrid();

            for (int l = 0; l < 4; l++)
            {
                byte signs = GetKSignsIQ2XS()[(int)((aux >> (7 * l)) & 127)];

                // Four magnitude bytes of each referenced entry, combined little-endian into one broadcast pair.
                int offA = qs[2 * l] * 4;
                uint gridA = (uint)(gridTable[offA] | (gridTable[offA + 1] << 8) | (gridTable[offA + 2] << 16) | (gridTable[offA + 3] << 24));
                int offB = qs[2 * l + 1] * 4;
                uint gridB = (uint)(gridTable[offB] | (gridTable[offB + 1] << 8) | (gridTable[offB + 2] << 16) | (gridTable[offB + 3] << 24));

                Vector128<sbyte> magnitudes = Vector128.Create((ulong)(((ulong)gridB << 32) | gridA)).AsSByte();
                Vector128<int> magLo = Sse41.ConvertToVector128Int32(magnitudes); // bytes 0..3 -> dword lanes (pmovsxbd, magnitudes all < 128)
                Vector128<int> magHi = Sse41.ConvertToVector128Int32(Ssse3.Shuffle(magnitudes.AsByte(), GetUpperBytesShuffle()).AsSByte()); // bytes 4..7 -> dword lanes

                float dbLocal = db;
                Vector128<float> dbV = Avx.BroadcastScalarToVector128(&dbLocal);
                Vector128<float> wLo = Sse.Multiply(Avx.ConvertToVector128Single(magLo), dbV); // cvtdq2ps then scale
                Vector128<float> wHi = Sse.Multiply(Avx.ConvertToVector128Single(magHi), dbV);

                Sse.Store(pStage + l * 8, Avx2.Xor(wLo.AsInt32(), SignMaskIQ2XS(signs, 0)).AsSingle());
                Sse.Store(pStage + l * 8 + 4, Avx2.Xor(wHi.AsInt32(), SignMaskIQ2XS(signs, 4)).AsSingle());
            }
        }
    }

    // Batched IQ3_XXS row: one staged sub-block feeds every vector's integer dot in RowDotIQ3XQ8Vector's integer and float
    // order, so the packed bytes are streamed once for the whole batch. Each vector keeps its own exact int32 super-block total.
    private static void BatchIQ3XQ8_Vector(byte* row, byte* qa, float* da, int blocks, int count, int rows, float* outBase, Q8KKernelOptions opts)
    {
        Span<byte> mag = stackalloc byte[32]; // magnitude bytes of the current 32-value sub-block
        Span<int> bsum = stackalloc int[MaxBatch]; // exact per-vector integer super-block totals
        Span<float> sumf = stackalloc float[MaxBatch];

        for (int bi = 0; bi < blocks; bi++)
        {
            byte* block = row + (long)bi * IQ3XxsBlockBytes;
            float dw = ReadHalfLE(block); // half-float weight scale, multiplied by each vector's activation scale in the reference order
            byte* qs = block + 2; // grid-index region: bytes [qs, qs+64) always inside the block

            for (int ib = 0; ib < 8; ib++)
            {
                uint aux = ReadIQ3AuxLE(qs + QkK / 4 + 4 * ib);
                int ls = 2 * (int)(aux >> 28) + 1;

                fixed (byte* pMag = mag)
                {
                    uint signs = StageIQ3XMagnitudes(qs + 8 * ib, aux, mag, opts.Grid); // decoded once per sub-block and reused across the batch
                    for (int b = 0; b < count; b++)
                    {
                        SubBlockDotQ8KVector(pMag, signs, (sbyte*)(qa + (long)b * blocks * QkK + bi * QkK + ib * 32), out int lo, out int hi, opts.Dot);
                        bsum[b] += (lo + hi) * ls;
                    }
                }
            }

            for (int b = 0; b < count; b++)
            {
                sumf[b] += (dw * da[(long)b * blocks + bi]) * bsum[b]; // same float grouping as the single-vector kernel
                bsum[b] = 0;
            }
        }

        for (int b = 0; b < count; b++)
        {
            outBase[(long)b * rows] = 0.25f * sumf[b]; // the reference's single final factor, applied exactly as in RowDotIQ3XQ8Vector
        }
    }

    // IQ3_XXS row expansion: w = db * grid byte, sign-applied through the sign table, per element. Same grid/sign
    // staging as RowDotIQ3XAvx2, storing the staged weights instead of dotting them.
    private static void DequantIQ3XAvx2(byte* row, float* outPtr, int cols)
    {
        Span<float> stage = stackalloc float[32]; // staging buffer for the current 32-value sub-block

        for (int baseIdx = 0; baseIdx < cols; baseIdx += QkK)
        {
            byte* block = row + (long)(baseIdx / QkK) * IQ3XxsBlockBytes;
            float dHalf = ReadHalfLE(block);

            for (int ib = 0; ib < 8; ib++)
            {
                int subStart = baseIdx + ib * 32;
                if (subStart >= cols)
                {
                    break; // zero-padded tail block: no elements left to consume.
                }

                uint aux = ReadIQ3AuxLE(block + 66 + 4 * ib);
                float db = dHalf * (0.5f + (aux >> 28)) * 0.5f;
                int limit = Math.Min(32, cols - subStart); // padded quants are zero: stop at the real column count.

                FillIQ3SubBlock(block + 2 + 8 * ib, aux, db, stage);

                fixed (float* pStage = stage)
                {
                    for (int c = 0; c + 8 <= limit; c += 8)
                    {
                        Avx.Store(outPtr + subStart + c, Avx.LoadVector256(pStage + c)); // staged weights, materialized once per sub-block
                    }
                }

                for (int l = (limit / 8) * 8; l < limit; l++)
                {
                    outPtr[subStart + l] = stage[l]; // partial final chunk: at most seven elements per sub-block
                }
            }
        }
    }
