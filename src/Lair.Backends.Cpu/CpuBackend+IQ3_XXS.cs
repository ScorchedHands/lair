    // IQ3_XXS: each 98-byte block covers 256 elements in eight 32-value sub-blocks ib. Sub-block ib reads its aux
    // word at scales_and_signs + 4*ib (block byte 66 + 4*ib): bits 28..31 give the sub-block scale, read back as
    // db = d * (0.5f + aux >> 28) * 0.5f; bits 0..27 pack four seven-bit sign-group codes, each selecting a row of
    // the shared sign table for the eight values of group l. Elements l*8..l*8+3 take grid entry qs[8ib+2l] and
    // elements l*8+4..l*8+7 entry qs[8ib+2l+1], byte j of each entry in little-endian order. w = db * grid byte,
    // sign-applied through the sign table. This is the literal scalar port of the reference dequant formula.
    private static float RowDotIQ3XQ8Scalar(byte* row, byte* qa, float* da, int cols, Q8KKernelOptions opts)
    {
        Span<byte> mag = stackalloc byte[32]; // magnitude bytes of the current 32-value sub-block
        int blocks = Q8KBlockCount(cols); // whole super-blocks: padding columns quantize to zero and contribute nothing
        float sumf = 0f;

        for (int bi = 0; bi < blocks; bi++)
        {
            byte* block = row + (long)bi * IQ3XxsBlockBytes;
            float d = ReadHalfLE(block) * da[bi]; // half-float weight scale times the activation block scale, reference order
            byte* qs = block + 2; // grid-index region: bytes [qs, qs+64) always inside the block
            int bsum = 0;

            for (int ib = 0; ib < 8; ib++)
            {
                uint aux = ReadIQ3AuxLE(qs + QkK / 4 + 4 * ib);
                uint signs = StageIQ3XMagnitudes(qs + 8 * ib, aux, mag, opts.Grid);

                int lo;
                int hi;

                fixed (byte* pMag = mag)
                {
                    SubBlockDotQ8KScalar(pMag, signs, (sbyte*)(qa + bi * QkK + ib * 32), out lo, out hi);
                }

                bsum += (lo + hi) * (2 * (int)(aux >> 28) + 1); // one ls covers the whole sub-block, as in the reference
            }

            sumf += d * bsum;
        }

        return 0.25f * sumf;
    }

