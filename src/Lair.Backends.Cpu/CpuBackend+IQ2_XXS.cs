    // IQ2_XXS: each 66-byte block covers 256 elements in eight 32-value sub-blocks ib. Sub-block ib reads its eight
    // aux bytes at qs + 4*ib (block byte 2 + 8*ib): the first four are the grid indices of the sub-block's four
    // eight-value groups, and the second word packs four seven-bit sign-group codes at bits 0..27 - each selecting a
    // row of the shared sign table for group l - plus the sub-block scale code at bits 28..31. The dot path is the
    // reference's integer form: ls = 2*(aux >> 28) + 1, grid magnitudes stay unsigned, each group's signs fold onto the
    // Q8_K activation quants instead of the weights, and the block scale multiplies an exact int32 sub-block total.
    // Grid entry aux8[l] carries the eight magnitude bytes of elements l*8..l*8+7 in little-endian order. sumf takes
    // d * bsum once per super-block in block order and 0.125f lands once at the end, so the scalar reference and the
    // AVX2 kernel run one shared float sequence over an integer total each of them computes exactly. Padded columns
    // carry zero quants under a scale built from real values only, so whole sub-blocks are safe to consume.
    private static float RowDotIQ2XXSQ8Scalar(byte* row, byte* qa, float* da, int cols, Q8KKernelOptions opts)
    {
        Span<byte> mag = stackalloc byte[32]; // magnitude bytes of the current 32-value sub-block
        int blocks = Q8KBlockCount(cols); // whole super-blocks: padding columns quantize to zero and contribute nothing
        float sumf = 0f;

        for (int bi = 0; bi < blocks; bi++)
        {
            byte* block = row + (long)bi * IQ2XxsBlockBytes;
            float d = ReadHalfLE(block) * da[bi]; // half-float weight scale times the activation block scale, reference order
            int bsum = 0;

            for (int ib = 0; ib < 8; ib++)
            {
                uint gridAux = ReadIQ2XXSGridLE(block + 2 + 8 * ib);
                uint signAux = ReadIQ2XXSSignsLE(block + 6 + 8 * ib);
                uint signs = StageIQ2XXSMagnitudes(gridAux, signAux, mag, opts.Grid);

                int lo;
                int hi;

                fixed (byte* pMag = mag)
                {
                    SubBlockDotQ8KScalar(pMag, signs, (sbyte*)(qa + bi * QkK + ib * 32), out lo, out hi);
                }

                bsum += (lo + hi) * (2 * (int)(signAux >> 28) + 1);
            }

            sumf += d * bsum;
        }

        return 0.125f * sumf;
    }

    // Vector integer dot: the same staged magnitudes and packed sign bytes feed SubBlockDotQ8KVector, whose lane totals -
    // pmaddubsw/pmaddwd under AVX2, vpdpbusd under AVX-VNNI - are exactly the scalar loop's running total. Only the float
    // accumulation order matters there, and it is shared: two paths over the same integer total. The activation side needs
    // no staging either: a sub-block of Q8_K quants is already contiguous bytes.
    private static float RowDotIQ2XXSQ8Vector(byte* row, byte* qa, float* da, int cols, Q8KKernelOptions opts)
    {
        Span<byte> mag = stackalloc byte[32]; // magnitude bytes of the current 32-value sub-block
        int blocks = Q8KBlockCount(cols); // whole super-blocks: padding columns quantize to zero and contribute nothing
        float sumf = 0f;

        for (int bi = 0; bi < blocks; bi++)
        {
            byte* block = row + (long)bi * IQ2XxsBlockBytes;
            float d = ReadHalfLE(block) * da[bi];
            int bsum = 0;

            for (int ib = 0; ib < 8; ib++)
            {
                uint gridAux = ReadIQ2XXSGridLE(block + 2 + 8 * ib);
                uint signAux = ReadIQ2XXSSignsLE(block + 6 + 8 * ib);
                uint signs = StageIQ2XXSMagnitudes(gridAux, signAux, mag, opts.Grid);

                int lo;
                int hi;

                fixed (byte* pMag = mag)
                {
                    SubBlockDotQ8KVector(pMag, signs, (sbyte*)(qa + bi * QkK + ib * 32), out lo, out hi, opts.Dot);
                }

                bsum += (lo + hi) * (2 * (int)(signAux >> 28) + 1);
            }

            sumf += d * bsum;
        }

        return 0.125f * sumf;
    }

    // Stage one IQ2_XXS sub-block: each of the four grid indices selects an eight-byte entry of the 256-entry table,
    // read as one unaligned ulong in element order (one indexed load covers a whole magnitude group), and the group's
    // seven-bit sign code is looked up in the shared sign table and packed back at byte l. Identical staging for both
    // dot paths and for every vector of a batch, which is what makes their results bit-identical.
    private static uint StageIQ2XXSMagnitudes(uint gridAux, uint signAux, Span<byte> mag, GridLoadEncoding grid)
    {
        fixed (byte* pGrid = GetIq2XXSGrid())
        fixed (byte* pMag = mag)
        {
            uint signs = 0;

            if (grid == GridLoadEncoding.Gather && Avx2.IsSupported)
            {
                // Hardware gather over whole entries: each lane's byte offset selects one four-byte half of an eight-byte entry, so the four groups' magnitude bytes land in element order from a single dword gather instead of four dependent indexed loads. Indices stay masked to the table width exactly as scalar indexing does, so no gathered address runs past the table.
                Vector256<int> offsets = Vector256.Create(
                    (int)(gridAux & 0xFF) * 8,
                    (int)(gridAux & 0xFF) * 8 + 4,
                    (int)((gridAux >> 8) & 0xFF) * 8,
                    (int)((gridAux >> 8) & 0xFF) * 8 + 4,
                    (int)((gridAux >> 16) & 0xFF) * 8,
                    (int)((gridAux >> 16) & 0xFF) * 8 + 4,
                    (int)(gridAux >> 24) * 8,
                    (int)(gridAux >> 24) * 8 + 4);

                Vector256<uint> gathered = Avx2.GatherVector256((uint*)pGrid, offsets, 1); // each dword lane gathers one half-entry raw: bits copied unchanged.
                Unsafe.WriteUnaligned(pMag, gathered); // all four groups land in element order at once - the same byte layout scalar staging writes group by group.

                for (int l = 0; l < 4; l++)
                {
                    signs |= (uint)GetKSignsIQ2XS()[(int)((signAux >> (7 * l)) & 127)] << (8 * l);
                }

                return signs;
            }

            for (int l = 0; l < 4; l++)
            {
                Unsafe.WriteUnaligned(pMag + 8 * l, Unsafe.ReadUnaligned<ulong>(pGrid + (nint)((gridAux >> (8 * l)) & 0xFF) * 8));
                signs |= (uint)GetKSignsIQ2XS()[(int)((signAux >> (7 * l)) & 127)] << (8 * l);
            }

            return signs;
        }
    }

    // IQ2_XXS sub-block staging: for each of the four eight-value groups, gather the referenced grid entry's eight
    // magnitude bytes into one broadcast vector (byte lanes 0..7 in element order), widen them with sign (pmovsxbd) so
    // every byte lands as its exact integer value, multiply by db, and flip the selected lanes by XOR-ing the float
    // sign bit (exact for every finite value, matching the reference multiply by -1.f). The staged weights land in
    // element order so the fused chunks match the scalar oracle.
    private static void FillIQ2XXSSubBlock(uint gridAux, uint signAux, float db, Span<float> stage)
    {
        fixed (float* pStage = stage)
        {
            ReadOnlySpan<byte> gridTable = GetIq2XXSGrid();

            for (int l = 0; l < 4; l++)
            {
                byte signs = GetKSignsIQ2XS()[(int)((signAux >> (7 * l)) & 127)];

                // Eight magnitude bytes of the referenced entry, combined little-endian into one broadcast vector.
                int off = (int)((gridAux >> (8 * l)) & 0xFF) * 8;
                ulong low = (uint)(gridTable[off] | (gridTable[off + 1] << 8) | (gridTable[off + 2] << 16) | (gridTable[off + 3] << 24));
                ulong high = (uint)(gridTable[off + 4] | (gridTable[off + 5] << 8) | (gridTable[off + 6] << 16) | (gridTable[off + 7] << 24));
                Vector128<sbyte> magnitudes = Vector128.Create(low | (high << 32)).AsSByte();
                Vector128<int> magLo = Sse41.ConvertToVector128Int32(magnitudes); // bytes 0..3 -> dword lanes (pmovsxbd, magnitudes all < 128)
                Vector128<int> magHi = Sse41.ConvertToVector128Int32(Ssse3.Shuffle(magnitudes.AsByte(), GetUpperBytesShuffle()).AsSByte()); // bytes 4..7 -> dword lanes

                float dbLocal = db;
                Vector128<float> dbV = Avx.BroadcastScalarToVector128(&dbLocal);
                Vector128<float> wLo = Sse.Multiply(Avx.ConvertToVector128Single(magLo), dbV); // cvtdq2ps then scale
                Vector128<float> wHi = Sse.Multiply(Avx.ConvertToVector128Single(magHi), dbV);

                Sse.Store(pStage + l * 8, Avx2.Xor(wLo.AsInt32(), SignMaskIQ2XS(signs, 0)).AsSingle());
                Sse.Store(pStage + l * 8 + 4, Avx2.Xor(wHi.AsInt32(), SignMaskIQ2XS(signs, 4)).AsSingle());
            }
        }
    }

    // Batched IQ2_XXS row against Q8_K activations: each sub-block's magnitudes and sign bytes are staged once, then
    // applied to every vector's activation quants in RowDotIQ2XXSQ8Vector's integer and float order, so the packed weight
    // bytes are streamed one time for the whole batch. The dot encoding is this backend's resolved one, identical to what
    // a solo GEMV of the same row runs.
    private static void BatchIQ2XXQ8_Vector(byte* row, byte* qa, float* da, int blocks, int count, int rows, float* outBase, Q8KKernelOptions opts)
    {
        Span<byte> mag = stackalloc byte[32]; // magnitude bytes of the current 32-value sub-block
        Span<int> bsum = stackalloc int[MaxBatch]; // exact per-vector integer super-block totals
        Span<float> sumf = stackalloc float[MaxBatch];

        for (int bi = 0; bi < blocks; bi++)
        {
            byte* block = row + (long)bi * IQ2XxsBlockBytes;
            float dw = ReadHalfLE(block); // half-float weight scale, multiplied by each vector's activation scale in the reference order

            for (int ib = 0; ib < 8; ib++)
            {
                uint gridAux = ReadIQ2XXSGridLE(block + 2 + 8 * ib);
                uint signAux = ReadIQ2XXSSignsLE(block + 6 + 8 * ib);
                uint signs = StageIQ2XXSMagnitudes(gridAux, signAux, mag, opts.Grid); // decoded once per sub-block and reused across the batch
                int ls = 2 * (int)(signAux >> 28) + 1;

                fixed (byte* pMag = mag)
                {
                    for (int b = 0; b < count; b++)
                    {
                        SubBlockDotQ8KVector(pMag, signs, (sbyte*)(qa + (long)b * blocks * QkK + bi * QkK + ib * 32), out int lo, out int hi, opts.Dot);
                        bsum[b] += (lo + hi) * ls;
                    }
                }
            }

            for (int b = 0; b < count; b++)
            {
                sumf[b] += (dw * da[(long)b * blocks + bi]) * bsum[b]; // same float grouping as the single-vector kernel
                bsum[b] = 0;
            }
        }

        for (int b = 0; b < count; b++)
        {
            outBase[(long)b * rows] = 0.125f * sumf[b]; // the reference's single final factor, applied exactly as in RowDotIQ2XXSQ8Vector
        }
    }

    // IQ2_XXS row expansion: w = db * grid byte, sign-applied through the sign table, per element. Same grid/sign
    // staging FillIQ2XXSSubBlock provides, storing the staged weights instead of dotting them.
    private static void DequantIQ2XXSAvx2(byte* row, float* outPtr, int cols)
    {
        Span<float> stage = stackalloc float[32]; // staging buffer for the current 32-value sub-block

        for (int baseIdx = 0; baseIdx < cols; baseIdx += QkK)
        {
            byte* block = row + (long)(baseIdx / QkK) * IQ2XxsBlockBytes;
            float dHalf = ReadHalfLE(block);

            for (int ib = 0; ib < 8; ib++)
            {
                int subStart = baseIdx + ib * 32;
                if (subStart >= cols)
                {
                    break; // zero-padded tail block: no elements left to consume.
                }

                uint gridAux = ReadIQ2XXSGridLE(block + 2 + 8 * ib);
                uint signAux = ReadIQ2XXSSignsLE(block + 6 + 8 * ib);
                float db = dHalf * (0.5f + (signAux >> 28)) * 0.25f;
                int limit = Math.Min(32, cols - subStart); // padded quants are zero: stop at the real column count.

                FillIQ2XXSSubBlock(gridAux, signAux, db, stage);

                fixed (float* pStage = stage)
                {
                    for (int c = 0; c + 8 <= limit; c += 8)
                    {
                        Avx.Store(outPtr + subStart + c, Avx.LoadVector256(pStage + c)); // staged weights, materialized once per sub-block
                    }
                }

                for (int l = (limit / 8) * 8; l < limit; l++)
                {
                    outPtr[subStart + l] = stage[l]; // partial final chunk: at most seven elements per sub-block
                }
            }
        }
    }
